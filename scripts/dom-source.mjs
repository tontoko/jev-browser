// Embed the DOM bundle into dist/dom-source.js so the SDK reads no package file at run time (Cloudflare Workers have none).
import { readFileSync, writeFileSync } from 'node:fs';
const bundle = readFileSync(new URL('../dist/dom.bundle.cjs', import.meta.url), 'utf8');
writeFileSync(new URL('../dist/dom-source.js', import.meta.url), `/** Generated by scripts/dom-source.mjs from dist/dom.bundle.cjs. */\nexport const domSource = ${JSON.stringify(bundle)};\n`);
